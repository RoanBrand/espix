#!/usr/bin/env bash
#
# Build htop as a U-mode espix app: upstream htop, upstream ncurses, and the
# small seam in this directory. The result is one static ET_EXEC ELF, the same
# kind every espix app is; there is no libc or curses to install beside it.
#
#   ./build.sh
#   scp build/htop esp@<host>:/bin/htop
#
# The device also needs the kernel side of the exercise -- /proc/stat, the
# per-process stat file, and /sys/devices/system/cpu/cpuN. See README.md.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
build="$here/build"
jobs="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"

gcc="$(command -v riscv32-esp-elf-gcc || true)"
if [ -z "$gcc" ]; then
    gcc="$(ls -d "$HOME"/.espressif/tools/riscv32-esp-elf/*/riscv32-esp-elf/bin/riscv32-esp-elf-gcc 2>/dev/null | tail -1)"
fi
[ -x "$gcc" ] || { echo "build: no riscv32-esp-elf-gcc" >&2; exit 1; }
ar="${gcc%gcc}ar"
ranlib="${gcc%gcc}ranlib"

# ncurses' fallback table is generated by the host's tic. macOS ships 6.0,
# which cannot parse ncurses 6.4's terminfo.src; a Homebrew/SDK one can.
tic_bin="${TIC:-}"
if [ -z "$tic_bin" ] && [ -x /opt/homebrew/opt/ncurses/bin/tic ]; then
    tic_bin=/opt/homebrew/opt/ncurses/bin/tic
fi
if [ -z "$tic_bin" ]; then
    tic_bin="$(command -v tic || true)"
fi
[ -x "$tic_bin" ] || { echo "build: no tic; ncurses needs one for its xterm fallback" >&2; exit 1; }
PATH="$(dirname "$tic_bin"):$PATH"

"$here/fetch-htop.sh"
"$here/fetch-ncurses.sh"

mkdir -p "$build/lib" "$build/ncurses" "$build/htop-build"

# libespix, the app-side runtime the linker will add. Building one tiny app is
# how espix-cc refreshes the archive.
printf 'int main(void){return 0;}\n' > "$build/null.c"
"$root/tools/espix-cc" "$build/null.c" -o "$build/null"
rm -f "$build/null" "$build/null.c"

# The two objects that are this port rather than upstream.
"$root/tools/espix-cc" -Os -I "$here/compat" -c "$here/espix_compat.c" -o "$build/espix_compat.o"
"$root/tools/espix-cc" -Os -I "$here/compat" -I "$here/sensors" \
    -c "$here/sensors/libsensors_espix.c" -o "$build/libsensors.o"
"$ar" rcs "$build/lib/libsensors.a" "$build/libsensors.o"

CFLAGS_COMMON="-Os -ffunction-sections -fdata-sections -march=rv32imafc_zicsr_zifencei_zaamo_zalrsc_zcb_zcmp_zcmt -mabi=ilp32f --specs=picolibc.specs"
CPPFLAGS_COMMON="-I$root/user/include -I$root/user/include/common"

echo "== ncurses"
cd "$build/ncurses"
cf_cv_have_tcgetattr=yes \
CC="$gcc" CFLAGS="$CFLAGS_COMMON" CPPFLAGS="$CPPFLAGS_COMMON" \
LIBS="$root/user/build/libespix.a" \
"$here/third_party/ncurses/configure" \
    --host=riscv32-esp-elf --disable-widec --without-cxx --without-ada \
    --without-progs --without-tests --without-manpages --with-termlib \
    --enable-termcap=no --with-fallbacks=xterm --disable-db-install \
    --without-debug --disable-stripping > "$build/ncurses.log" 2>&1
make -j"$jobs" AR="$ar" RANLIB="$ranlib" >> "$build/ncurses.log" 2>&1

NC="$build/ncurses"

echo "== htop"
cd "$build/htop-build"
CC="$gcc" \
CFLAGS="$CFLAGS_COMMON -I$here/compat -I$root/user/include -I$root/user/include/common" \
CPPFLAGS="-I$here/sensors" LDFLAGS="-L$build/lib" \
LIBS="$root/user/build/libespix.a" \
CURSES_CFLAGS="-I$NC/include" \
CURSES_LIBS="$NC/lib/libncurses.a $NC/lib/libtinfo.a $root/user/build/libespix.a" \
"$here/third_party/htop/configure" \
    --host=riscv32-linux-gnu --disable-unicode --disable-affinity \
    --disable-delayacct --disable-hwloc --disable-capabilities \
    --enable-static --enable-sensors > "$build/htop-configure.log" 2>&1

# The link goes through espix-cc, which adds crt0, libespix and user/uapp.ld.
# am__append_7 is htop's -rdynamic, a flag the RISC-V GCC driver does not take.
make -j"$jobs" htop \
    CC="$root/tools/espix-cc" am__append_7= \
    CFLAGS="-Os -ffunction-sections -fdata-sections -I$here/compat -I$root/user/include -I$root/user/include/common" \
    LIBS="$build/espix_compat.o -L$build/lib -lsensors $NC/lib/libncurses.a $NC/lib/libtinfo.a" \
    > "$build/htop-make.log" 2>&1

"$root/tools/espix-cc" --strip htop "$build/htop"
echo "== built $build/htop ($(wc -c < "$build/htop" | tr -d ' ') bytes)"
