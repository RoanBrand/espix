#!/usr/bin/env python3
"""espix's syscalls, against Linux's rv32 numbers.

    tools/syscalls.py --check    fail if a call in the Linux list is not Linux's number, one of
                                 espix's own is below ESPIX_SYS_OWN, two share a number, or
                                 docs/POSIX.md's table is not this list (the build runs it)
    tools/syscalls.py --write    rewrite docs/POSIX.md's table from the list

The list is components/espix_proc/include/espix_syscall.h: a call Linux has with the
same arguments and meaning takes Linux's number, named in its comment where Linux's
name differs ("Linux's mmap2"); the rest are espix's own, from 2048.
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HEADER = REPO / "components/espix_proc/include/espix_syscall.h"
DOC = REPO / "docs/POSIX.md"
BEGIN, END = "<!-- syscalls.py: begin -->", "<!-- syscalls.py: end -->"

# Linux's asm-generic numbers for rv32 (include/uapi/asm-generic/unistd.h), for the calls
# espix shares: rv32 has only the time64 calls, and passes a 64-bit offset as a register pair.
RV32 = {
    "getcwd": 17, "dup": 23, "fcntl64": 25, "ioctl": 29, "truncate64": 45, "ftruncate64": 46,
    "chdir": 49, "openat": 56, "close": 57, "pipe2": 59, "read": 63, "write": 64, "pread64": 67, "pwrite64": 68,
    "readlinkat": 78, "fsync": 82, "exit_group": 94, "sched_yield": 124, "kill": 129, "rt_sigreturn": 139,
    "setpgid": 154, "getpgid": 155, "getsid": 156, "setsid": 157, "uname": 160, "umask": 166, "getpid": 172,
    "getppid": 173, "getuid": 174, "geteuid": 175, "getgid": 176, "getegid": 177, "gettid": 178,
    "socket": 198, "bind": 200, "listen": 201, "connect": 203, "getsockname": 204,
    "getpeername": 205, "sendto": 206, "recvfrom": 207, "setsockopt": 208, "getsockopt": 209,
    "shutdown": 210, "brk": 214, "munmap": 215, "execve": 221, "mmap2": 222, "mprotect": 226,
    "msync": 227, "mincore": 232, "madvise": 233, "accept4": 242, "getrandom": 278,
    "clock_gettime64": 403, "futex_time64": 422,
}

ENTRY = re.compile(r"X\((\w+),\s*(\w+),\s*(\d+)\)\s*/\*\s*(.*?)\s*\*/")


def lists():
    """(linux, own, own_base): each list [(name, number, linux name or None, args)]."""
    text = HEADER.read_text(encoding="utf-8")
    base = int(re.search(r"#define ESPIX_SYS_OWN (\d+)", text).group(1))

    def body(macro):
        m = re.search(r"#define %s\(X\)(.*?)(?:\n\n|\n#)" % macro, text, re.S)
        if not m:
            sys.exit(f"syscalls: no {macro} in {HEADER}")
        out = []
        for name, lname, nr, comment in ENTRY.findall(m.group(1)):
            alias = re.search(r"; Linux's (\w+)$", comment)
            args = re.sub(r"; Linux's \w+$", "", comment)
            out.append((lname, int(nr), alias.group(1) if alias else None, args))
        return out

    return body("ESPIX_SYSCALLS_LINUX"), body("ESPIX_SYSCALLS_OWN"), base


def problems(linux, own, base):
    found = []
    seen = {}
    for name, nr, alias, _ in linux + own:
        if nr in seen:
            found.append(f"{name} and {seen[nr]} are both {nr}")
        seen[nr] = name
    for name, nr, alias, _ in linux:
        want = RV32.get(alias or name)
        if want is None:
            found.append(f"{name} is in the Linux list, but rv32 has no {alias or name}")
        elif want != nr:
            found.append(f"{name} is {nr}; Linux's {alias or name} is {want}")
    for name, nr, _, _ in own:
        if nr < base:
            found.append(f"{name} is espix's own, but {nr} is below {base}")
    return found


def table(linux, own, base):
    cell = lambda t: t.replace("|", "\\|")
    rows = ["| call | number | Linux's | arguments |", "|---|---|---|---|"]
    for name, nr, alias, args in sorted(linux, key=lambda e: e[1]):
        rows.append(f"| `{name}` | {nr} | {'`' + alias + '`' if alias else 'the same'} | {cell(args)} |")
    for name, nr, _, args in sorted(own, key=lambda e: e[1]):
        rows.append(f"| `{name}` | {nr} | espix's own | {cell(args)} |")
    return "\n".join(rows)


def section(linux, own, base):
    return (f"{BEGIN}\n{len(linux)} calls take Linux's rv32 numbers, with Linux's arguments and "
            f"meaning (flag, errno and structure values are picolibc's and lwIP's); {len(own)} are "
            f"espix's own, from {base}. Generated by `tools/syscalls.py --write` from "
            f"`components/espix_proc/include/espix_syscall.h`.\n\n{table(linux, own, base)}\n{END}")


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("--check", "--write"):
        sys.exit(__doc__)
    linux, own, base = lists()
    found = problems(linux, own, base)
    doc = DOC.read_text(encoding="utf-8")
    want = section(linux, own, base)
    if BEGIN in doc and END in doc:
        a, b = doc.index(BEGIN), doc.index(END) + len(END)
        have, new = doc[a:b], doc[:a] + want + doc[b:]
    else:
        have, new = None, doc.rstrip("\n") + "\n\n### Syscalls\n\n" + want + "\n"
    if sys.argv[1] == "--write":
        if found:
            sys.exit("syscalls: " + "\n  ".join(found))
        DOC.write_text(new, encoding="utf-8")
        return 0
    if have != want:
        found.append("docs/POSIX.md's table is not the list: run tools/syscalls.py --write")
    if found:
        sys.exit("syscalls: " + "\n  ".join(found))
    print(f"syscalls: {len(linux)} at Linux's rv32 numbers, {len(own)} espix's own from {base}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
